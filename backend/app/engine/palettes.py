def _build(palette_id: str, name: str, craft: str, entries) -> Palette:
    codes = [code for code, _, _ in entries]
    if len(codes) != len(set(codes)):
        duplicates = sorted({c for c in codes if codes.count(c) > 1})
        raise ValueError(f"IDs duplicados en la paleta {palette_id}: {duplicates}")
    return Palette(
        id=palette_id,
        name=name,
        craft=craft,  # type: ignore[arg-type]
        colors=[PaletteColor(id=code, name=color_name, hex=hex_value) for code, color_name, hex_value in entries],
    )


HAMA_MIDI = _build("hama_midi", "Hama Midi", "hama", _HAMA)
DMC = _build("dmc", "DMC", "cross_stitch", _DMC)

PALETTES: dict[str, Palette] = {HAMA_MIDI.id: HAMA_MIDI, DMC.id: DMC}


def all_palettes() -> list[Palette]:
    """Las dos paletas del contrato, en orden estable."""
    return [HAMA_MIDI, DMC]


def get_palette(palette_id: str | None = None, craft: str = "hama") -> Palette:
    """Devuelve la paleta pedida o la de por defecto para la técnica.

    Lanza ``KeyError`` si el id no existe (el router lo traduce a 404).
    """
    if palette_id:
        key = palette_id.strip().lower()
        if key not in PALETTES:
            raise KeyError(palette_id)
        return PALETTES[key]
    return DMC if craft == "cross_stitch" else HAMA_MIDI
